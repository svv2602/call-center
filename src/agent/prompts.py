def _add_business_days(start_date: datetime.date, days: int) -> datetime.date:
    """Add *days* business days (Mon-Fri) to *start_date*."""
    current = start_date
    added = 0
    while added < days:
        current += datetime.timedelta(days=1)
        if current.weekday() < 5:  # Mon=0 … Fri=4
            added += 1
    return current


