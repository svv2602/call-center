def format_storage_context(data: dict) -> str | None:
    """Format 1C storage contracts into a Ukrainian prompt section.

    Returns ``None`` when there are no contracts to report.
    """
    contracts = data.get("contracts") if isinstance(data, dict) else None
    if not contracts:
        return None

    lines: list[str] = []
    lines.append("## Зберігання шин клієнта (автоматична перевірка за CallerID)")
    lines.append(f"Знайдено {len(contracts)} договір(ів):")

    has_warehouse = False
    for i, c in enumerate(contracts, 1):
        number = c.get("contract_number", "?")
        owner = c.get("owner_name", "")
        header = f"{i}. Договір {number}"
        if owner:
            header += f" ({owner})"
        lines.append(header + ":")

        for tire in c.get("tires", []):
            qty = tire.get("quantity", "?")
            brand = tire.get("brand", "")
            model = tire.get("model", "")
            size = tire.get("size", "")
            season_key = tire.get("season", "")
            season = _SEASON_UA.get(season_key, season_key)
            lines.append(f"   - {qty}× {brand} {model} {size} ({season})")

        location = c.get("location", "")
        loc_text = _LOCATION_UA.get(location, location)
        lines.append(f"   - Місцезнаходження: {loc_text}")

        if location == "warehouse":
            has_warehouse = True

        debt = c.get("debt", 0)
        if debt and debt > 0:
            lines.append(f"   - Борг: {debt} грн")
        else:
            lines.append("   - Борг: немає")

    if has_warehouse:
        min_date = _add_business_days(datetime.date.today(), 3)
        lines.append(f"⚡ Мінімальна дата запису на монтаж: {min_date.isoformat()} (3 робочих дні)")

    lines.append("⚡ Одразу озвуч клієнту інформацію про його шини на зберіганні.")
    return "\n".join(lines)


def build_system_prompt_with_context(
    base_prompt: str,
    *,
    is_modular: bool = False,
    order_stage: str | None = None,
    safety_context: str | None = None,
    few_shot_context: str | None = None,
    promotions_context: str | None = None,
    caller_phone: str | None = None,
    order_id: str | None = None,
    pattern_context: str | None = None,
    agent_name: str | None = None,
    customer_profile: str | None = None,
    caller_history: str | None = None,
    storage_context: str | None = None,
    tools_called: set[str] | None = None,
    scenario: str | None = None,
    active_scenarios: set[str] | None = None,
    selected_station: dict[str, Any] | None = None,
    selected_slot: dict[str, str] | None = None,
    offered_slots: list[dict[str, str]] | None = None,
    fitting_progress: dict[str, Any] | None = None,
    enabled_tools: set[str] | None = None,
) -> str:
    """Build the final system prompt with all dynamic context injected.

    This replaces the duplicated _build_system_prompt() methods in agent.py
    and streaming_loop.py with a single shared implementation.

    Args:
        base_prompt: The base system prompt (modular or DB-loaded).
        is_modular: Whether the base prompt was assembled via assemble_prompt().
                    Stage injection only applies to modular prompts.
        order_stage: Current order stage (from compute_order_stage).
        safety_context: Training safety rules section.
        few_shot_context: Few-shot dialogue examples section.
        promotions_context: Active promotions section.
        caller_phone: CallerID phone number (masked if PII vault active).
        order_id: Current order draft ID.
        pattern_context: Pattern injection text from conversation patterns.
        agent_name: Tenant-specific agent name (overrides default "Олена").
        active_scenarios: All scenarios detected during this call (accumulated).
                         Used to add modules when customer switches topics.

    Returns:
        Final system prompt string ready to send to LLM.
    """
    # Replace default agent name with tenant-specific name
    if agent_name and agent_name != "Олена":
        base_prompt = base_prompt.replace("Тебе звати Олена", f"Тебе звати {agent_name}")
        base_prompt = base_prompt.replace("ти Олена", f"ти {agent_name}")

    # Upgrade from compact router to full scenario modules when scenario
    # is detected mid-call (first turn was compact, now we know the topic).
    if is_modular and scenario and _COMPACT_MARKER in base_prompt:
        base_prompt = assemble_prompt(
            scenario=scenario,
            include_pronunciation=False,
            enabled_tools=enabled_tools,
        )
        logger.info("Compact→full upgrade: scenario=%s", scenario)

    # Topic switching: when customer changes topic mid-call, add modules
    # from newly detected scenarios (only add, never remove).
    if is_modular and active_scenarios and scenario:
        primary_mods = _modules_for_scenario(scenario, enabled_tools) or _ALL_SCENARIO_MODULES
        base_modules = set(primary_mods)
        extra: list[str] = []
        seen: set[int] = {id(m) for m in base_modules}
        for sc in active_scenarios:
            if sc == scenario:
                continue
            for mod in _modules_for_scenario(sc, enabled_tools) or []:
                mod_id = id(mod)
                if mod_id not in seen:
                    extra.append(mod)
                    seen.add(mod_id)
        if extra:
            base_prompt = base_prompt + "\n" + "\n".join(extra)
            logger.info(
                "Topic switch expansion: primary=%s, added modules from %s",
                scenario,
                active_scenarios - {scenario},
            )

    # Dynamic module expansion: if tools were called that require modules
    # not in the current scenario, append them to the base prompt.
    if is_modular and tools_called:
        extra_modules = infer_expanded_modules(scenario, tools_called)
        if extra_modules:
            base_prompt = base_prompt + "\n" + "\n".join(extra_modules)
            logger.info(
                "Module expansion: scenario=%s, added %d modules from tools %s",
                scenario,
                len(extra_modules),
                tools_called,
            )

    # ---------------------------------------------------------------
    # Section ordering for implicit cache (Gemini 2.5 Flash, etc.):
    #   STABLE prefix (same across all turns within a call) →
    #   DYNAMIC suffix (changes every turn).
    # The LLM provider caches the longest matching prefix, so putting
    # stable content first maximises cache hits and saves ~90% on
    # cached tokens.
    # ---------------------------------------------------------------

    parts = [base_prompt]

    # --- STABLE sections (constant within a single call) ---

    # Current date and season hint (fixed for the call's day)
    today = datetime.date.today()
    weekday_names = [
        "понеділок",
        "вівторок",
        "середа",
        "четвер",
        "п'ятниця",
        "субота",
        "неділя",
    ]
    month_names = [
        "",
        "січня",
        "лютого",
        "березня",
        "квітня",
        "травня",
        "червня",
        "липня",
        "серпня",
        "вересня",
        "жовтня",
        "листопада",
        "грудня",
    ]
    weekday_name = weekday_names[today.weekday()]

    # Precomputed lookup for the next 10 days. LLMs are unreliable at
    # date arithmetic (real prod failure 2026-08-04: LLM computed
    # «пʼятницю» as Aug 6 / Wed instead of Aug 7 / Fri), so we hand it
    # a ready table — no math required. Format: "Пн 4 серпня (сьогодні)".
    date_table_lines = []
    for offset in range(10):
        d = today + datetime.timedelta(days=offset)
        wd = weekday_names[d.weekday()]
        row = f"- {wd.capitalize()} {d.day} {month_names[d.month]} (ISO {d.isoformat()})"
        if offset == 0:
            row += " ← сьогодні"
        elif offset == 1:
            row += " ← завтра"
        elif offset == 2:
            row += " ← післязавтра"
        date_table_lines.append(row)

    parts.append(
        f"\n## Поточна дата"
        f"\nСьогодні: {weekday_name}, {today.day} {month_names[today.month]} {today.year} року"
        f"\nISO: {today.isoformat()}"
        f"\n\n**Таблиця найближчих 10 днів — використовуй ТІЛЬКИ її для обчислення відносних дат:**\n"
        + "\n".join(date_table_lines)
        + "\n\nКоли клієнт каже «завтра», «пʼятницю», «наступний тиждень» — знайди відповідний рядок таблиці, "
        "витягни ISO-дату звідти. НЕ рахуй сам — це джерело помилок."
    )

    # Dynamic season hint
    month = today.month
    if month in (11, 12, 1, 2, 3):
        hint = "Зараз зимовий сезон — запитай: «Зимові чи всесезонні?»"
    elif month in (5, 6, 7, 8, 9):
        hint = "Зараз літній сезон — запитай: «Літні чи всесезонні?»"
    else:  # April, October
        hint = "Зараз міжсезоння — запитай: «Літні, зимові чи всесезонні?»"

    parts.append(f"\n## Підказка по сезону\n- {hint}")
    parts.append("- Якщо клієнт обирає нетиповий сезон — не заперечуй, виконуй запит")

    # Safety rules, few-shot examples, and promotions (stable per call)
    if safety_context:
        parts.append(safety_context)
    if few_shot_context:
        parts.append(few_shot_context)
    if promotions_context:
        parts.append(promotions_context)

    # Customer profile, caller history and storage contracts (stable per call)
    if customer_profile:
        parts.append("\n" + customer_profile)

    if caller_history:
        parts.append("\n" + caller_history)

    if storage_context:
        parts.append("\n" + storage_context)

    # --- DYNAMIC sections (change between turns) ---

    # Stage-aware injection (modular prompts only)
    if is_modular and order_stage:
        if order_stage == "delivery_set":
            parts.append(_STAGE_ORDER_CONFIRMATION)
        elif order_stage == "confirmed":
            parts.append(_STAGE_OFFER_FITTING)

    if caller_phone or order_id:
        parts.append("\n## Контекст дзвінка")
        if caller_phone:
            parts.append(f"- CallerID клієнта: {caller_phone}")
        if order_id:
            parts.append(f"- Поточне замовлення (чорновик): {order_id}")

    if pattern_context:
        parts.append(pattern_context)

    if selected_station:
        sid = selected_station.get("id", "")
        city = selected_station.get("city", "")
        address = selected_station.get("address", "")
        district = selected_station.get("district", "")
        phone = selected_station.get("phone", "")
        block = [
            "\n## 📍 Обрана точка шиномонтажу (використовуй ТІЛЬКИ ці дані, не вигадуй іншу адресу!)",
            f"- station_id: {sid}",
        ]
        if city:
            block.append(f"- Місто: {city}")
        if address:
            block.append(f"- Адреса: {address}")
        if district:
            block.append(f"- Район: {district}")
        if phone:
            block.append(f"- Телефон: {phone}")
        block.append(
            "- ⛔ Якщо клієнт хоче іншу точку — обов'язково спочатку виклич "
            "get_fitting_stations, а потім говори нову адресу з результату."
        )
        parts.append("\n".join(block))

    if selected_slot:
        sdate = selected_slot.get("date", "")
        stime = selected_slot.get("time", "")
        slot_block = [
            "\n## 📅 Обраний слот шиномонтажу (використовуй ТІЛЬКИ ці дату/час!)",
        ]
        if sdate:
            slot_block.append(f"- Дата: {sdate}")
        if stime:
            slot_block.append(f"- Час: {stime}")
        slot_block.append(
            "- ⛔ У book_fitting передавай саме ці date/time. НЕ ВИГАДУЙ інші!"
        )
        slot_block.append(
            "- ⛔ У підтвердженні клієнту озвуч саме цю дату/час. "
            "Якщо клієнт хоче іншу дату — виклич get_fitting_slots ЩЕ РАЗ."
        )
        parts.append("\n".join(slot_block))
    elif offered_slots:
        dates = sorted({s["date"] for s in offered_slots if s.get("date")})
        if dates:
            times_by_date: dict[str, list[str]] = {}
            for s in offered_slots:
                d = s.get("date", "")
                t = s.get("time", "")
                if d and t:
                    times_by_date.setdefault(d, []).append(t)
            today_iso = datetime.date.today().isoformat()
            slot_block = [
                "\n## 📅 Запропоновані слоти шиномонтажу (клієнт ще обирає)",
                f"- ⛔ У book_fitting.date передавай ТІЛЬКИ дату з цього списку (НЕ {today_iso} — це сьогодні!)",
                "- ⛔ У book_fitting.time передавай ТІЛЬКИ час з цього списку",
                "- ⛔ Якщо клієнт назвав час не зі списку — використай найближчий вільний зі списку",
            ]
            for d in dates:
                times = ", ".join(sorted(set(times_by_date.get(d, []))))
                slot_block.append(f"- {d}: {times}")
            parts.append("\n".join(slot_block))

    # --- Fitting progress block ---
    # Surfaces already-collected data so LLM won't loop back to Krok 2/3/4
    # after passing through them. See _build_fitting_progress in this file.
    if fitting_progress and any(fitting_progress.values()):
        progress_text = _render_fitting_progress(fitting_progress)
        if progress_text:
            parts.append(progress_text)

    return "\n".join(parts)


def _render_fitting_progress(p: dict[str, Any]) -> str:
    """Render fitting progress block for LLM.

    Reads collected state and produces a checklist with ✅/⏳ markers and
    a single «НАСТУПНИЙ КРОК» pointer, so the LLM does not re-ask completed
    steps under attention dilution (recurring bug from calls 07-30/07-31).
    """
    # Fields in Krok order: 0=name, 1=city+station, 2=storage, 3=date,
    # 4=time, 5=plate, 6=brand, 7=phone (from CallerID), 8=confirm.
    name = p.get("customer_name")
    city = p.get("city")
    station_addr = p.get("station_address")
    storage_choice = p.get("storage_choice")   # "own" | "contract" | None
    storage_contract = p.get("storage_contract")
    date = p.get("date")
    time_ = p.get("time")
    plate = p.get("plate")
    brand = p.get("brand")
    caller_phone = p.get("caller_phone")
    booked = bool(p.get("booked"))
    requested_weekday = p.get("requested_weekday")  # int 0..6 or None

    if booked:
        return (
            "\n## 📋 Прогрес запису"
            "\n✅ ЗАПИС СТВОРЕНО. Далі — тільки прощання або новий сценарій "
            "(наприклад другий договір, консультація)."
        )

    checklist: list[tuple[str, bool, str]] = []
    checklist.append(("Ім'я", bool(name), name or "ще не назвали"))
    if city or station_addr:
        parts_addr = []
        if city:
            parts_addr.append(city)
        if station_addr:
            parts_addr.append(station_addr)
        checklist.append(("Місто/точка", True, ", ".join(parts_addr)))
    else:
        checklist.append(("Місто/точка", False, "не обрано"))
    storage_desc = "не з'ясовано"
    if storage_choice == "own":
        storage_desc = "клієнт привозить свої"
    elif storage_choice == "contract":
        storage_desc = (
            f"зі зберігання (договір {storage_contract})"
            if storage_contract
            else "зі зберігання (договір ЗАФІКСОВАНИЙ у сесії, передавай storage_contract)"
        )
    checklist.append(("Зберігання", storage_choice is not None, storage_desc))
    # Date row: if not yet chosen but client mentioned a weekday earlier —
    # surface it so the LLM doesn't re-ask ("клієнт просив пʼятницю").
    if not date and requested_weekday is not None:
        _wd_names = [
            "понеділок", "вівторок", "середу", "четвер",
            "пʼятницю", "суботу", "неділю",
        ]
        date_desc = (
            f"клієнт ЩЕ РАНІШЕ просив {_wd_names[requested_weekday]} — "
            f"НЕ ПИТАЙ ще раз, одразу виклич get_fitting_slots(date_from=найближча {_wd_names[requested_weekday]})"
        )
        checklist.append(("Дата", False, date_desc))
    else:
        checklist.append(("Дата", bool(date), date or "не обрано"))
    checklist.append(("Час", bool(time_), time_ or "не обрано"))
    checklist.append(("Держномер", bool(plate), plate or "не назвали"))
    checklist.append(("Марка авто", bool(brand), brand or "не назвали"))
    checklist.append(("Телефон", bool(caller_phone), caller_phone or "нема CallerID"))

    # Find next step — first "not done"
    next_step_idx = next(
        (i for i, (_, done, _) in enumerate(checklist) if not done), None
    )
    step_labels = [
        "Крок 0 (Ім'я)",
        "Крок 1 (Місто/точка)",
        "Крок 2 (Зберігання)",
        "Крок 3 (Дата)",
        "Крок 4 (Час)",
        "Крок 5 (Держномер)",
        "Крок 6 (Марка авто)",
        "Крок 7 (Телефон — з CallerID)",
    ]

    lines = ["\n## 📋 Прогрес запису"]
    for label, done, value in checklist:
        marker = "✅" if done else "⏳"
        lines.append(f"{marker} {label}: {value}")

    if next_step_idx is None:
        lines.append(
            "\n**НАСТУПНИЙ КРОК: Крок 8 (Підтвердження).** "
            "Всі поля зібрано — сформулюй підтвердження і чекай «так» → book_fitting."
        )
    else:
        next_label = step_labels[next_step_idx]
        lines.append(f"\n**НАСТУПНИЙ КРОК: {next_label}.**")

    lines.append(
        "⛔ **ЗАБОРОНЕНО ставити питання про пункти з ✅** — вони вже зібрані. "
        "Клієнт має явно сказати «змінимо»/«ні, інше», щоб ти повернувся. "
        "Інакше — тільки НАСТУПНИЙ КРОК."
    )
    return "\n".join(lines)


